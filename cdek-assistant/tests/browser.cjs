const { chromium } = require('playwright');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawn } = require('child_process');
const assert = require('assert/strict');
const project = path.resolve(__dirname, '..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'cdek-browser-'));
const port = 18081;
const server = spawn('python3', [path.join(__dirname, 'browser_fixture.py'), temp, String(port), process.env.CDEK_TEST_SOURCE_DB || '/workspace/cdek-private/app.sqlite3'], {cwd:project,stdio:['ignore','pipe','pipe']});
let browser;
(async () => {
  for (let i=0;i<100;i++) { if(fs.existsSync(path.join(temp,'credentials.json'))) break; await new Promise(r=>setTimeout(r,100)); }
  const password=JSON.parse(fs.readFileSync(path.join(temp,'credentials.json'),'utf8')).password;
  browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const url=`http://127.0.0.1:${port}`;
  await page.goto(url);await page.locator('#login-form').waitFor({state:'visible'});
  assert.equal(await page.locator('#workspace').isVisible(),false);
  await page.fill('#username','browser-admin');await page.fill('#password',password);await page.locator('#login-form button').click();
  await page.locator('#workspace').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.getElementById('source-count').textContent==='206');
  assert.equal(await page.locator('#approved-count').innerText(),'0');
  await page.fill('#question','Духи, несколько флаконов 100 мл, авиа, нет документов');await page.click('#ask-button');
  await page.getByRole('heading',{name:'Нужна проверка источников'}).waitFor();
  assert.ok((await page.locator('#answer').innerText()).includes('Условия перевозки не определены'));
  fs.mkdirSync('/workspace/cdek-private/screenshots',{recursive:true});await page.screenshot({path:'/workspace/cdek-private/screenshots/assistant-desktop.png',fullPage:true});
  await page.click('#sources-tab');await page.locator('.source-row').first().waitFor();
  await page.fill('#review-query','духи');await page.locator('#review-search button').click();
  await page.locator('#review-results .citation').first().waitFor();
  assert.ok((await page.locator('#review-results').innerText()).includes('Только для проверки'));
  await page.fill('#source-filter','395');await page.locator('#source-list button').first().click();
  await page.locator('#source-detail').waitFor({state:'visible'});
  await page.locator('#source-detail').getByText('История версий источника',{exact:true}).waitFor();
  assert.ok((await page.locator('#source-detail').innerText()).includes('История версий источника'));
  assert.ok((await page.locator('#source-detail').innerText()).includes('packaging-addendum'));
  const original=await page.request.get(url+'/api/admin/original?id=395');assert.equal(original.status(),200);assert.ok((await original.text()).includes('Полный текст DOM страницы 395'));
  await page.click('#queue-tab');await page.locator('.queue-row').first().waitFor();
  await page.click('#audit-tab');await page.locator('.audit-row').first().waitFor();
  await page.click('[data-tab=assistant]');await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/workspace/cdek-private/screenshots/assistant-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.click('#logout');await page.locator('#login-form').waitFor({state:'visible'});
  await page.fill('#username','browser-operator');await page.fill('#password',password);await page.locator('#login-form button').click();await page.locator('#workspace').waitFor({state:'visible'});
  assert.equal(await page.locator('#sources-tab').isVisible(),false);
  const offline=await browser.newPage();
  await offline.route('**/health',r=>r.fulfill({status:200,contentType:'text/html',body:'<html>Static page</html>'}));
  await offline.goto(url);
  await offline.getByText('По этому адресу сервер приложения недоступен.',{exact:false}).waitFor();
  assert.equal(await offline.locator('#login-form button').isDisabled(),true);
  await offline.close();
  const missingScript=await browser.newPage();
  await missingScript.route('**/app.js',r=>r.abort());
  await missingScript.goto(url);
  assert.equal(await missingScript.locator('#connection-status').isVisible(),true);
  assert.equal(await missingScript.locator('#login-form button').isDisabled(),true);
  await missingScript.close();
  assert.deepEqual(errors,[]);
  console.log('PASS browser: private login, coverage, honest no-source response, admin review search, addendum/version history, queue, audit, logout, operator role, mobile overflow, no page errors.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.kill('SIGTERM');await new Promise(r=>server.once('exit',r));fs.rmSync(temp,{recursive:true,force:true});});
